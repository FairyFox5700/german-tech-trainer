import {chromium} from 'file:///C:/Users/tysch/AppData/Local/hermes/skills/creative/linkedin-one-pager/scripts/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';

const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1280,height:800}});
const page = await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
assert.match(await page.locator('main h1').innerText(),/Today/);
await page.locator('[data-action="start-daily"]').click();
assert.ok((await page.locator('#cardHeading').innerText()).length>2);
await page.locator('[data-action="reveal"]').click();
assert.equal(await page.locator('[data-rating]').count(),4);
await page.locator('[data-rating="good"]').click();
await page.waitForTimeout(250);
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('werkwort.state.v1')));
assert.equal(saved.activity[Object.keys(saved.activity)[0]].studied,1);
await page.goto('http://127.0.0.1:4173/#/progress');
await page.waitForTimeout(100);
assert.match(await page.locator('main h1').innerText(),/Progress/);
await page.goto('http://127.0.0.1:4173/#/library');
await page.waitForTimeout(100);
assert.equal(await page.locator('.word-row').count(),50);
await page.setViewportSize({width:320,height:568});
await page.waitForTimeout(100);
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
assert.ok(overflow<=0,`mobile overflow: ${overflow}px`);
assert.equal(errors.length,0,`browser errors: ${errors.join(' | ')}`);
console.log(JSON.stringify({learn:true,reviewPersisted:true,progress:true,libraryCount:50,mobileOverflow:overflow,errors},null,2));
await browser.close();
