import {chromium} from 'file:///C:/Users/tysch/AppData/Local/hermes/skills/creative/linkedin-one-pager/scripts/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';

const base=(process.env.BASE_URL || 'http://127.0.0.1:4173').replace(/\/$/,'');
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1280,height:800}});
const page = await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto(`${base}/`,{waitUntil:'networkidle'});
assert.match(await page.locator('main h1').innerText(),/Today/);
await page.locator('[data-action="start-daily"]').click();
assert.ok((await page.locator('#cardHeading').innerText()).length>2);
await page.locator('[data-action="reveal"]').click();
assert.equal(await page.locator('[data-rating]').count(),4);
const savedTerm=await page.locator('#cardHeading').innerText();
await page.locator('[data-save-id]').click();
let savedState=await page.evaluate(()=>JSON.parse(localStorage.getItem('werkwort.state.v1')));
assert.equal(savedState.savedIds.length,1);
await page.locator('[data-rating="good"]').click();
await page.waitForTimeout(250);
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('werkwort.state.v1')));
assert.equal(saved.activity[Object.keys(saved.activity)[0]].studied,1);
await page.locator('[data-action="pause"]').click();
await page.goto(`${base}/#/learn`);
await page.waitForTimeout(100);
assert.equal(await page.locator('.saved-dashboard').count(),1);
assert.match(await page.locator('.saved-dashboard').innerText(),new RegExp(savedTerm.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
await page.goto(`${base}/#/progress`);
await page.waitForTimeout(100);
assert.match(await page.locator('main h1').innerText(),/Progress/);
await page.goto(`${base}/#/library`);
await page.waitForTimeout(100);
assert.equal(await page.locator('.word-row').count(),150);
await page.goto(`${base}/#/library?saved=1`);
await page.waitForTimeout(100);
assert.equal(await page.locator('.word-row').count(),1);
await page.setViewportSize({width:320,height:568});
await page.waitForTimeout(100);
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
assert.ok(overflow<=0,`mobile overflow: ${overflow}px`);
await page.evaluate(async()=>{await navigator.serviceWorker.ready; return true;});
await context.setOffline(true);
await page.reload({waitUntil:'domcontentloaded'});
await page.waitForSelector('main h1');
assert.match(await page.locator('main h1').innerText(),/Vocabulary library/);
await context.setOffline(false);
assert.equal(errors.length,0,`browser errors: ${errors.join(' | ')}`);
console.log(JSON.stringify({learn:true,savedDashboard:true,savedLibraryFilter:true,reviewPersisted:true,progress:true,libraryCount:150,mobileOverflow:overflow,offlineReload:true,errors},null,2));
await browser.close();
